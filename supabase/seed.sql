Тироцит (также тиреоцит или фолликулярная клетка) — это основной вид эпителиальных клеток, из которых состоят фолликулы щитовидной железы. Их главная функция — захват йода и синтез жизненно важных тиреоидных гормонов: тироксина (Т4) и трийодтиронина (Т3), которые регулируют обмен веществ в организме.

Тироцит — клетка кубической или уплощённой формы (форма меняется в зависимости от активности железы: чем активнее работает — тем выше клетки), и у неё, как у любой эпителиальной клетки, есть две принципиально разные поверхности.

