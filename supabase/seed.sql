Анти-ТПО — это аутоантитела (обычно IgG), которые организм вырабатывает против этого фермента. Их появление — маркёр аутоиммунной агрессии против щитовидной железы.

Что это такое

ТПО — это не гормон, а фермент (гем-содержащая пероксидаза), ключевой фермент синтеза тиреоидных гормонов. Без него щитовидная железа физически не может произвести ни Т3, ни Т4, сколько бы йода и тиреоглобулина ни было в наличии.

Где и откуда выделяется

Синтезируется в тироцитах (фолликулярных клетках щитовидной железы) и располагается на апикальной мембране этих клеток — то есть на границе клетки с коллоидом фолликула, где как раз и происходит синтез гормонов. Это мембраносвязанный фермент, он не «выделяется» в кровь как гормон, а работает локально, встроенный в мембрану.

Что она делает (механизм)

ТПО — многофункциональный катализатор, выполняет сразу несколько шагов синтеза гормонов:
1. Окисление йодида (I⁻) в реактивный йод
2. Органификация — присоединение йода к остаткам тирозина тиреоглобулина: МИТ и ДИТ
3. Конденсация: ДИТ + ДИТ → Т4, МИТ + ДИТ → Т3

То есть буквально вся «сборка» гормонов на молекулярном уровне держится на этом одном ферменте.

